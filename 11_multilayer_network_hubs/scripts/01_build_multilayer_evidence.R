suppressPackageStartupMessages({
    library(ggplot2)
})

regions <- c("EC","HIP","MTG","PC","SFG","VCX")

dir.create("results",showWarnings=FALSE)
dir.create("tables",showWarnings=FALSE)
dir.create("figures",showWarnings=FALSE)

# ============================================================
# 1. REGIONAL DIFFERENTIAL-EXPRESSION EVIDENCE
# ============================================================

message("1/5 Reading regional differential-expression results...")

regional <- list()

for(reg in regions){

    f <- paste0(
        "input/regional_DEA/",
        reg,
        "_gene_level_AD_vs_Control.tsv"
    )

    if(!file.exists(f)){
        warning("Missing regional DEA: ",reg)
        next
    }

    x <- read.delim(
        f,
        stringsAsFactors=FALSE
    )

    x <- x[
        !is.na(x$Gene) &
        is.finite(x$logFC) &
        is.finite(x$adj.P.Val),
    ]

    x <- x[
        !duplicated(x$Gene),
    ]

    x$Region <- reg

    regional[[reg]] <- x
}

if(length(regional)==0)
    stop("No regional DEA results available.")

allDE <- do.call(
    rbind,
    regional
)

rownames(allDE) <- NULL

genes <- sort(
    unique(allDE$Gene)
)

cat("Gene universe:",length(genes),"\n")

# ============================================================
# REGIONAL SUMMARY PER GENE
# ============================================================

regional_summary <- do.call(
    rbind,
    lapply(genes,function(g){

        z <- allDE[
            allDE$Gene==g,
        ]

        sig <- z$adj.P.Val < .05 &
               abs(z$logFC) >= .5

        sig_up <- sig & z$logFC > 0
        sig_down <- sig & z$logFC < 0

        n_sig <- sum(sig,na.rm=TRUE)

        dominant_direction <- if(
            sum(sig_up) > sum(sig_down)
        ){
            "Up"
        } else if(
            sum(sig_down) > sum(sig_up)
        ){
            "Down"
        } else {
            "Mixed/None"
        }

        consistency <- if(n_sig>0){
            max(
                sum(sig_up),
                sum(sig_down)
            ) / n_sig
        } else {
            0
        }

        data.frame(
            Gene=g,

            Regions_tested=nrow(z),

            DEG_regions=n_sig,

            Up_regions=sum(
                sig_up,
                na.rm=TRUE
            ),

            Down_regions=sum(
                sig_down,
                na.rm=TRUE
            ),

            Direction_consistency=
                consistency,

            Dominant_direction=
                dominant_direction,

            Mean_logFC=
                mean(
                    z$logFC,
                    na.rm=TRUE
                ),

            Mean_abs_logFC=
                mean(
                    abs(z$logFC),
                    na.rm=TRUE
                ),

            Best_FDR=
                min(
                    z$adj.P.Val,
                    na.rm=TRUE
                )
        )
    })
)

# ============================================================
# 2. WGCNA EVIDENCE
# ============================================================

message("2/5 Adding WGCNA evidence...")

regional_summary$WGCNA_module <- NA_character_
regional_summary$Module_membership <- NA_real_
regional_summary$GS_AD <- NA_real_
regional_summary$GS_AD_FDR <- NA_real_

module_file <- "input/WGCNA_gene_modules.tsv"

if(file.exists(module_file)){

    m <- read.delim(
        module_file,
        stringsAsFactors=FALSE
    )

    regional_summary$WGCNA_module <-
        m$Module[
            match(
                regional_summary$Gene,
                m$Gene
            )
        ]
}

gs_file <- "input/WGCNA_gene_significance_AD.tsv"

if(file.exists(gs_file)){

    gs <- read.delim(
        gs_file,
        stringsAsFactors=FALSE
    )

    idx <- match(
        regional_summary$Gene,
        gs$Gene
    )

    regional_summary$GS_AD <-
        gs$GS_AD[idx]

    regional_summary$GS_AD_FDR <-
        gs$FDR[idx]
}

# Module membership table generated by WGCNA contains
# genes as row names when read with row.names=1.
mm_file <- "input/WGCNA_module_membership.tsv"

if(file.exists(mm_file)){

    mm <- tryCatch(
        read.delim(
            mm_file,
            row.names=1,
            check.names=FALSE
        ),
        error=function(e) NULL
    )

    if(!is.null(mm)){

        for(i in seq_len(nrow(regional_summary))){

            g <- regional_summary$Gene[i]
            mod <- regional_summary$WGCNA_module[i]

            if(
                !is.na(mod) &&
                g %in% rownames(mm)
            ){

                col <- paste0("ME",mod)

                if(col %in% colnames(mm)){
                    regional_summary$Module_membership[i] <-
                        mm[g,col]
                }
            }
        }
    }
}

# ============================================================
# 3. REGULATORY NETWORK SUPPORT
# ============================================================

message("3/5 Adding regulatory-network evidence...")

regional_summary$Regulatory_regions <- 0
regional_summary$Regulatory_TFs <- 0
regional_summary$Regulatory_edges <- 0

regfile <- "input/regulatory_edges.tsv"

if(file.exists(regfile)){

    e <- read.delim(
        regfile,
        stringsAsFactors=FALSE
    )

    if(
        all(
            c("target","Region") %in%
            names(e)
        )
    ){

        for(i in seq_len(nrow(regional_summary))){

            g <- regional_summary$Gene[i]

            z <- e[
                e$target==g,
            ]

            if(nrow(z)>0){

                regional_summary$Regulatory_regions[i] <-
                    length(
                        unique(z$Region)
                    )

                regional_summary$Regulatory_edges[i] <-
                    nrow(z)

                tfcol <- if(
                    "TF" %in% names(z)
                ){
                    "TF"
                } else if(
                    "source" %in% names(z)
                ){
                    "source"
                } else {
                    NA_character_
                }

                if(!is.na(tfcol)){

                    regional_summary$Regulatory_TFs[i] <-
                        length(
                            unique(
                                z[[tfcol]]
                            )
                        )
                }
            }
        }
    }
}

# ============================================================
# 4. SINGLE-NUCLEUS SUPPORT
# ============================================================

message("4/5 Adding single-nucleus evidence...")

celltypes <- c(
    "Neuron",
    "Astrocyte",
    "Microglia",
    "Oligodendrocyte",
    "OPC",
    "Endothelial"
)

regional_summary$snRNA_celltypes_tested <- 0
regional_summary$snRNA_support_celltypes <- 0
regional_summary$snRNA_direction_concordant <- 0
regional_summary$snRNA_max_abs_logFC <- NA_real_

# EC is used for bulk ↔ snRNA directional comparison
EC <- regional[["EC"]]

if(!is.null(EC)){

    for(ct in celltypes){

        f <- paste0(
            "input/single_nucleus/GSE138852_",
            ct,
            "_AD_vs_Control.tsv"
        )

        if(!file.exists(f)){
            message(
                "  snRNA result unavailable: ",
                ct
            )
            next
        }

        sn <- read.delim(
            f,
            stringsAsFactors=FALSE
        )

        if(!all(
            c(
                "Gene",
                "logFC",
                "adj.P.Val"
            ) %in% names(sn)
        )){
            next
        }

        idx_sn <- match(
            regional_summary$Gene,
            sn$Gene
        )

        idx_ec <- match(
            regional_summary$Gene,
            EC$Gene
        )

        available <-
            !is.na(idx_sn) &
            !is.na(idx_ec)

        regional_summary$snRNA_celltypes_tested[
            available
        ] <-
            regional_summary$snRNA_celltypes_tested[
                available
            ] + 1

        snFC <- rep(
            NA_real_,
            nrow(regional_summary)
        )

        snFDR <- rep(
            NA_real_,
            nrow(regional_summary)
        )

        bulkFC <- rep(
            NA_real_,
            nrow(regional_summary)
        )

        snFC[available] <-
            sn$logFC[
                idx_sn[available]
            ]

        snFDR[available] <-
            sn$adj.P.Val[
                idx_sn[available]
            ]

        bulkFC[available] <-
            EC$logFC[
                idx_ec[available]
            ]

        support <-
            available &
            is.finite(snFDR) &
            snFDR < .05

        concordant <-
            support &
            sign(snFC) ==
            sign(bulkFC)

        regional_summary$snRNA_support_celltypes[
            support
        ] <-
            regional_summary$snRNA_support_celltypes[
                support
            ] + 1

        regional_summary$snRNA_direction_concordant[
            concordant
        ] <-
            regional_summary$snRNA_direction_concordant[
                concordant
            ] + 1

        for(i in which(available)){

            value <- abs(
                snFC[i]
            )

            if(!is.finite(value))
                next

            old <- regional_summary$snRNA_max_abs_logFC[i]

            if(
                is.na(old) ||
                value > old
            ){
                regional_summary$snRNA_max_abs_logFC[i] <-
                    value
            }
        }
    }
}

# ============================================================
# 5. MULTILAYER PRIORITIZATION
# ============================================================

message("5/5 Calculating integrated evidence scores...")

# ------------------------------------------------------------
# Each layer contributes a bounded score from 0 to 1.
# This prevents a layer with many measurements from
# overwhelming the others.
# ------------------------------------------------------------

regional_summary$S_DE_recurrence <-
    pmin(
        regional_summary$DEG_regions /
        length(regions),
        1
    )

regional_summary$S_direction <-
    regional_summary$Direction_consistency

regional_summary$S_effect <-
    pmin(
        regional_summary$Mean_abs_logFC / 2,
        1
    )

regional_summary$S_WGCNA <-
    ifelse(
        is.finite(
            regional_summary$Module_membership
        ),
        pmin(
            abs(
                regional_summary$Module_membership
            ),
            1
        ),
        0
    )

regional_summary$S_GS <-
    ifelse(
        is.finite(
            regional_summary$GS_AD
        ),
        pmin(
            abs(
                regional_summary$GS_AD
            ),
            1
        ),
        0
    )

regional_summary$S_regulatory <-
    pmin(
        regional_summary$Regulatory_regions /
        length(regions),
        1
    )

regional_summary$S_snRNA <-
    ifelse(
        regional_summary$snRNA_celltypes_tested>0,
        regional_summary$snRNA_direction_concordant /
        regional_summary$snRNA_celltypes_tested,
        0
    )

# ------------------------------------------------------------
# Equal-weight evidence-layer score
#
# We deliberately avoid optimizing weights against the same
# dataset used to generate the evidence.
# ------------------------------------------------------------

score_cols <- c(
    "S_DE_recurrence",
    "S_direction",
    "S_effect",
    "S_WGCNA",
    "S_GS",
    "S_regulatory",
    "S_snRNA"
)

regional_summary$Layers_available <-
    rowSums(
        cbind(
            rep(1,nrow(regional_summary)),
            rep(1,nrow(regional_summary)),
            rep(1,nrow(regional_summary)),
            is.finite(
                regional_summary$Module_membership
            ),
            is.finite(
                regional_summary$GS_AD
            ),
            rep(
                file.exists(regfile),
                nrow(regional_summary)
            ),
            regional_summary$snRNA_celltypes_tested>0
        )
    )

regional_summary$Integrated_score <-
    rowMeans(
        regional_summary[
            ,
            score_cols
        ],
        na.rm=TRUE
    )

# Require multiple independent evidence types for
# "high-confidence" descriptive prioritization.
regional_summary$Evidence_layers_positive <-
    rowSums(
        regional_summary[
            ,
            score_cols
        ] >= .5,
        na.rm=TRUE
    )

regional_summary <- regional_summary[
    order(
        -regional_summary$Evidence_layers_positive,
        -regional_summary$Integrated_score,
        -regional_summary$DEG_regions,
        -regional_summary$Mean_abs_logFC
    ),
]

regional_summary$Priority_rank <-
    seq_len(
        nrow(regional_summary)
    )

write.table(
    regional_summary,
    "tables/GSE5281_multilayer_gene_prioritization.tsv",
    sep="\t",
    quote=FALSE,
    row.names=FALSE
)

# ============================================================
# HIGH-CONFIDENCE CANDIDATE SET
# ============================================================

high <- regional_summary[
    regional_summary$Evidence_layers_positive >= 4 &
    regional_summary$DEG_regions >= 2,
]

write.table(
